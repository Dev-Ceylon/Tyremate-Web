#!/usr/bin/env node
/**
 * Pre-build step:
 *  1. Bundles SQL migrations and print templates into CommonJS modules so the
 *     backend can run without a filesystem (browser worker / static hosting).
 *  2. Copies the sql.js WebAssembly binary into /public.
 */
import { createHash } from "node:crypto"
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const platformDir = join(root, "backend", "platform")
mkdirSync(platformDir, { recursive: true })

function readSqlDir(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf-8").replace(/^\uFEFF/, "") }))
}

const migrations = readSqlDir(join(root, "backend/packages/database/migrations"))
const repeatable = readSqlDir(join(root, "backend/packages/database/repeatable_migrations"))
const schemaHash = createHash("sha256")
  .update(JSON.stringify(migrations) + JSON.stringify(repeatable))
  .digest("hex")
  .slice(0, 16)

writeFileSync(
  join(platformDir, "migrations.generated.js"),
  `// AUTO-GENERATED by scripts/prepare.mjs - do not edit.\n` +
    `module.exports = {\n` +
    `  SCHEMA_HASH: ${JSON.stringify(schemaHash)},\n` +
    `  MIGRATIONS: ${JSON.stringify(migrations, null, 2)},\n` +
    `  REPEATABLE_MIGRATIONS: ${JSON.stringify(repeatable, null, 2)},\n` +
    `}\n`,
)

const templatesDir = join(root, "backend/apps/electron/services/templates")
const templates = Object.fromEntries(
  readdirSync(templatesDir)
    .filter((f) => f.endsWith(".html"))
    .sort()
    .map((f) => [f, readFileSync(join(templatesDir, f), "utf-8")]),
)
writeFileSync(
  join(platformDir, "templates.generated.js"),
  `// AUTO-GENERATED by scripts/prepare.mjs - do not edit.\nmodule.exports = ${JSON.stringify(templates, null, 2)}\n`,
)

const wasmSrc = join(root, "node_modules/sql.js/dist/sql-wasm.wasm")
mkdirSync(join(root, "public"), { recursive: true })
copyFileSync(wasmSrc, join(root, "public/sql-wasm.wasm"))

console.log(
  `prepare: ${migrations.length} migrations, ${repeatable.length} repeatable, ${Object.keys(templates).length} templates, schema ${schemaHash}`,
)

// 3. User manual for the in-app Help page (+ fallback copies of its screenshots;
//    the primary copies are served from Cloudinary).
mkdirSync(join(root, "public/manual"), { recursive: true })
for (const file of readdirSync(join(root, "docs/images"))) {
  copyFileSync(join(root, "docs/images", file), join(root, "public/manual", file))
}
const manual = readFileSync(join(root, "docs/USER_MANUAL.md"), "utf-8")
writeFileSync(
  join(root, "src/features/help/manual.generated.ts"),
  `// AUTO-GENERATED by scripts/prepare.mjs from docs/USER_MANUAL.md - do not edit.\nexport const USER_MANUAL_MARKDOWN = ${JSON.stringify(manual)}\n`,
)
