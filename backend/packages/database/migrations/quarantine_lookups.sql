CREATE TABLE IF NOT EXISTS QuarantineSourceM (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  SourceCode TEXT NOT NULL UNIQUE,
  SourceName TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS QuarantineStatusM (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  StatusCode TEXT NOT NULL UNIQUE,
  StatusName TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS QuarantineMovementActionM (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  ActionCode TEXT NOT NULL UNIQUE,
  ActionName TEXT NOT NULL
);
