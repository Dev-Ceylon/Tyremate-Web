CREATE TABLE IF NOT EXISTS PO (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER,
  StatusID INTEGER,
  Category TEXT NOT NULL DEFAULT 'tyre',
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  IsSupplierApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsSupplierApproved IN (0, 1)),
  Date TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (SoID) REFERENCES SO(SoID),
  FOREIGN KEY (StatusID) REFERENCES StatusM(Id)
);

CREATE TABLE IF NOT EXISTS POTyres (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  POID INTEGER NOT NULL,
  TyreID INTEGER NOT NULL,
  Price REAL NOT NULL DEFAULT 0,
  Discount REAL NOT NULL DEFAULT 0,
  Qty INTEGER NOT NULL DEFAULT 1,
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  StatusID INTEGER,
  FOREIGN KEY (POID) REFERENCES PO(ID),
  FOREIGN KEY (TyreID) REFERENCES TyreM(Id),
  FOREIGN KEY (StatusID) REFERENCES StatusM(Id),
  UNIQUE (POID, TyreID)
);

CREATE TABLE IF NOT EXISTS PoTyresSuppliers (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  PoTyresID INTEGER NOT NULL,
  Qty INTEGER NOT NULL DEFAULT 1,
  SupplierID INTEGER NOT NULL,
  IsApproved INTEGER CHECK (IsApproved IN (0, 1)),
  ExpectedDeliveryDate DATE,
  ActualDeliveryDate DATE,
  FOREIGN KEY (PoTyresID) REFERENCES POTyres(ID),
  FOREIGN KEY (SupplierID) REFERENCES SupplierM(SupplierID),
  UNIQUE (PoTyresID, SupplierID)
);

CREATE TABLE IF NOT EXISTS PoTyreAllocations (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  POID INTEGER NOT NULL,
  PoTyresID INTEGER NOT NULL,
  LocationId INTEGER NOT NULL,
  FOREIGN KEY (POID) REFERENCES PO(ID),
  FOREIGN KEY (PoTyresID) REFERENCES POTyres(ID),
  FOREIGN KEY (LocationId) REFERENCES StorageLocationM(Id),
  UNIQUE (POID, PoTyresID)
);
