CREATE TABLE IF NOT EXISTS ContractorM (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Name VARCHAR,
  Rating INT
);

CREATE TABLE IF NOT EXISTS ContractorContact (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ContractorID INTEGER NOT NULL,
  PhoneNumber TEXT NOT NULL,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (ContractorID) REFERENCES ContractorM(ID)
);

CREATE TABLE IF NOT EXISTS ContractorEmail (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ContractorID INTEGER NOT NULL,
  EmailAddress TEXT NOT NULL,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (ContractorID) REFERENCES ContractorM(ID)
);

CREATE TABLE IF NOT EXISTS ContractorAddress (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ContractorID INTEGER NOT NULL,
  AddressType TEXT,
  AddressLine1 TEXT,
  AddressLine2 TEXT,
  City TEXT,
  State TEXT,
  PostalCode TEXT,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (ContractorID) REFERENCES ContractorM(ID)
);

CREATE TABLE IF NOT EXISTS ContractorTyre (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  ContractorID INTEGER NOT NULL,
  TyreID INTEGER NOT NULL,
  FOREIGN KEY (ContractorID) REFERENCES ContractorM(ID),
  FOREIGN KEY (TyreID) REFERENCES TyreM(Id)
);
