CREATE TABLE IF NOT EXISTS SupplierM (
  SupplierID INTEGER PRIMARY KEY AUTOINCREMENT,
  SupplierCode TEXT NOT NULL UNIQUE,
  Name TEXT NOT NULL,
  TinNo TEXT,
  VatNo TEXT
);

CREATE TABLE IF NOT EXISTS SupplierContact (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SupplierID INTEGER NOT NULL,
  PhoneNumber TEXT NOT NULL,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (SupplierID) REFERENCES SupplierM(SupplierID)
);

CREATE TABLE IF NOT EXISTS SupplierEmail (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SupplierID INTEGER NOT NULL,
  EmailAddress TEXT NOT NULL,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (SupplierID) REFERENCES SupplierM(SupplierID)
);

CREATE TABLE IF NOT EXISTS SupplierAddress (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SupplierID INTEGER NOT NULL,
  AddressType TEXT,
  AddressLine1 TEXT,
  AddressLine2 TEXT,
  City TEXT,
  State TEXT,
  PostalCode TEXT,
  IsPrimary INTEGER NOT NULL DEFAULT 0 CHECK (IsPrimary IN (0, 1)),
  FOREIGN KEY (SupplierID) REFERENCES SupplierM(SupplierID)
);
