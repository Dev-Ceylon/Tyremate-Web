CREATE TABLE IF NOT EXISTS Inquiry (
  InquiryID INTEGER PRIMARY KEY AUTOINCREMENT,
  Date TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Category TEXT NOT NULL DEFAULT 'tyre',
  CustomerID INTEGER,
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  Notes TEXT,
  ConvertedSOID INTEGER,
  IsCompleted INTEGER NOT NULL DEFAULT 0 CHECK (IsCompleted IN (0, 1)),
  SalesRepID INTEGER,
  FOREIGN KEY (CustomerID) REFERENCES CustomerM(CustomerID),
  FOREIGN KEY (ConvertedSOID) REFERENCES SO(SoID),
  FOREIGN KEY (SalesRepID) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_inquiry_sales_rep ON Inquiry (SalesRepID);

CREATE TABLE IF NOT EXISTS InquiryWalkinCustomer (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  InquiryID INTEGER NOT NULL UNIQUE,
  CustomerName TEXT NOT NULL,
  CustomerPhone TEXT NOT NULL,
  CustomerAddress TEXT NOT NULL,
  CustomerEmail TEXT,
  VehicleNumber TEXT,
  TinNo TEXT,
  VatNo TEXT,
  FOREIGN KEY (InquiryID) REFERENCES Inquiry(InquiryID)
);

CREATE TABLE IF NOT EXISTS InquiryTyres (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  InquiryID INTEGER NOT NULL,
  TyreID INTEGER NOT NULL,
  Price REAL NOT NULL DEFAULT 0,
  Discount REAL NOT NULL DEFAULT 0,
  Qty INTEGER NOT NULL DEFAULT 1,
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  FOREIGN KEY (InquiryID) REFERENCES Inquiry(InquiryID),
  FOREIGN KEY (TyreID) REFERENCES TyreM(Id)
);

CREATE TABLE IF NOT EXISTS InquiryReminder (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  InquiryID INTEGER NOT NULL,
  ReminderID INTEGER NOT NULL,
  ReminderDate TEXT NOT NULL,
  ReminderNote TEXT,
  IsDone INTEGER NOT NULL DEFAULT 0,
  FOREIGN KEY (InquiryID) REFERENCES Inquiry(InquiryID),
  FOREIGN KEY (ReminderID) REFERENCES Reminders(ID)
);
