CREATE TABLE IF NOT EXISTS PoTyreBatches (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  PoTyresID INTEGER NOT NULL,
  DOT TEXT,
  Qty INTEGER NOT NULL DEFAULT 0 CHECK (Qty > 0),
  CreatedBy TEXT,
  createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (PoTyresID) REFERENCES POTyres(ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_po_tyre_batches_potyresid ON PoTyreBatches (PoTyresID);