CREATE TABLE IF NOT EXISTS StorageManager (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  TyreId INTEGER NOT NULL,
  LocationID INTEGER NOT NULL,
  Qty INTEGER NOT NULL DEFAULT 0 CHECK (Qty >= 0),
  OrderID INTEGER,
  SourceTypeId INTEGER,
  SourceId INTEGER,
  CreatedBy TEXT,
  createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (TyreId) REFERENCES TyreM(Id),
  FOREIGN KEY (LocationID) REFERENCES StorageLocationM(Id),
  FOREIGN KEY (SourceTypeId) REFERENCES StorageSourceM(Id)
);
