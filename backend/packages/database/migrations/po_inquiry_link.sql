CREATE TABLE IF NOT EXISTS InquiryPO (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  InquiryID INTEGER NOT NULL,
  POID INTEGER NOT NULL,
  CreatedBy TEXT,
  createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (InquiryID) REFERENCES Inquiry(InquiryID) ON DELETE CASCADE,
  FOREIGN KEY (POID) REFERENCES PO(ID) ON DELETE CASCADE,
  UNIQUE (InquiryID, POID)
);

CREATE INDEX IF NOT EXISTS idx_inquiry_po_inquiry ON InquiryPO(InquiryID);
CREATE INDEX IF NOT EXISTS idx_inquiry_po_po ON InquiryPO(POID);
