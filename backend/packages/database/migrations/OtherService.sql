CREATE TABLE IF NOT EXISTS OtherService (
  OSID INTEGER PRIMARY KEY AUTOINCREMENT,
  Date TEXT NOT NULL DEFAULT (DATE('now')),
  IsCompleted INTEGER NOT NULL DEFAULT 0 CHECK (IsCompleted IN (0, 1)),
  IsPaymentCompleted INTEGER NOT NULL DEFAULT 0 CHECK (IsPaymentCompleted IN (0, 1))
);

CREATE TABLE IF NOT EXISTS OtherServiceCustomer (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  OSID INTEGER NOT NULL,
  CustomerID INTEGER NULL,
  FOREIGN KEY (OSID) REFERENCES OtherService(OSID),
  FOREIGN KEY (CustomerID) REFERENCES CustomerM(CustomerID)
);

CREATE TABLE IF NOT EXISTS OtherServiceCustomerDetail (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  OSID INTEGER NOT NULL,
  CustomerName TEXT NOT NULL,
  CustomerPhone TEXT,
  CustomerEmail TEXT,
  FOREIGN KEY (OSID) REFERENCES OtherService(OSID)
);

CREATE TABLE IF NOT EXISTS OtherServiceConsumables (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  OSID INTEGER NOT NULL,
  ConsumableID INTEGER NOT NULL,
  Price REAL NOT NULL DEFAULT 0,
  Qty INTEGER NOT NULL DEFAULT 1,
  FOREIGN KEY (OSID) REFERENCES OtherService(OSID),
  FOREIGN KEY (ConsumableID) REFERENCES ConsumableM(Id)
);

CREATE TABLE IF NOT EXISTS OtherServicePayments (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  OSID INTEGER NOT NULL,
  PaymentID INTEGER NOT NULL,
  FOREIGN KEY (OSID) REFERENCES OtherService(OSID),
  FOREIGN KEY (PaymentID) REFERENCES Payments(ID)
);
