CREATE TABLE IF NOT EXISTS ConsumableM (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  Name TEXT NOT NULL,
  Category TEXT,
  Unit TEXT NOT NULL DEFAULT 'Piece',
  CostPrice REAL DEFAULT 0,
  ReorderLevel INTEGER DEFAULT 0,
  IsActive INTEGER DEFAULT 1,
  CreatedDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  ModifiedDate DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ConsumableLocationM (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  LocationCode TEXT,
  LocationName TEXT,
  BranchId INTEGER,
  LocationTypeId INTEGER,
  Capacity INTEGER,
  FOREIGN KEY (BranchId) REFERENCES BranchM(Id),
  FOREIGN KEY (LocationTypeId) REFERENCES StorageLocationTypeM(Id)
);

CREATE TABLE IF NOT EXISTS ConsumableStorageManager (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  ConsumableID INTEGER NOT NULL,
  LocationID INTEGER NOT NULL,
  Qty INTEGER NOT NULL DEFAULT 0 CHECK (Qty >= 0),
  BatchNumber TEXT,
  ExpiryDate TEXT,
  createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ConsumableID) REFERENCES ConsumableM(Id),
  FOREIGN KEY (LocationID) REFERENCES ConsumableLocationM(Id)
);
