CREATE TABLE IF NOT EXISTS InquirySO (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  InquiryID INTEGER NOT NULL,
  SOID INTEGER NOT NULL,
  CreatedBy TEXT,
  createdDate DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (InquiryID) REFERENCES Inquiry(InquiryID) ON DELETE CASCADE,
  FOREIGN KEY (SOID) REFERENCES SO(SoID) ON DELETE CASCADE,
  UNIQUE (InquiryID, SOID)
);

CREATE INDEX IF NOT EXISTS idx_inquiry_so_inquiry ON InquirySO(InquiryID);
CREATE INDEX IF NOT EXISTS idx_inquiry_so_so ON InquirySO(SOID);
