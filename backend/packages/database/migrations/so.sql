CREATE TABLE IF NOT EXISTS SO (
  SoID INTEGER PRIMARY KEY AUTOINCREMENT,
  Date TEXT NOT NULL,
  Category TEXT NOT NULL DEFAULT 'tyre',
  CreatedDateTime DATETIME DEFAULT (datetime('now', 'localtime')),
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  IsCompleted INTEGER NOT NULL DEFAULT 0 CHECK (IsCompleted IN (0, 1)),
  IsPaymentCompleted INTEGER NOT NULL DEFAULT 0 CHECK (IsPaymentCompleted IN (0, 1))
);

CREATE TABLE IF NOT EXISTS SoCustomer (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER NOT NULL,
  CustomerID INTEGER NOT NULL,
  FOREIGN KEY (SoID) REFERENCES SO(SoID),
  FOREIGN KEY (CustomerID) REFERENCES CustomerM(CustomerID)
);

CREATE TABLE IF NOT EXISTS SoWalkinCustomer (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER NOT NULL,
  CustomerName TEXT NOT NULL,
  CustomerPhone TEXT NOT NULL,
  CustomerAddress TEXT NOT NULL,
  CustomerEmail TEXT,
  VehicleNumber TEXT,
  TinNo TEXT,
  VatNo TEXT,
  FOREIGN KEY (SoID) REFERENCES SO(SoID)
);

CREATE TABLE IF NOT EXISTS SoTyres (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER NOT NULL,
  TyreID INTEGER NOT NULL,
  Price REAL NOT NULL DEFAULT 0,
  Discount REAL NOT NULL DEFAULT 0,
  Qty INTEGER NOT NULL DEFAULT 1,
  NeedToOrderQty INTEGER NOT NULL DEFAULT 0,
  IsAdminApproved INTEGER NOT NULL DEFAULT 0 CHECK (IsAdminApproved IN (0, 1)),
  FOREIGN KEY (SoID) REFERENCES SO(SoID),
  FOREIGN KEY (TyreID) REFERENCES TyreM(Id)
);

CREATE TABLE IF NOT EXISTS ManufactureOrder (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER NOT NULL,
  FOREIGN KEY (SoID) REFERENCES SO(SoID)
);

CREATE TABLE IF NOT EXISTS SoTyreStorageAllocation (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  SoTyreID INTEGER NOT NULL,
  StorageManagerID INTEGER,
  StorageManagerBatchID INTEGER,
  Qty INTEGER NOT NULL CHECK (Qty > 0),
  CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (SoTyreID) REFERENCES SoTyres(ID),
  FOREIGN KEY (StorageManagerID) REFERENCES StorageManager(Id)
);

CREATE INDEX IF NOT EXISTS idx_so_tyre_storage_allocation_batch
ON SoTyreStorageAllocation (StorageManagerBatchID);

CREATE TABLE IF NOT EXISTS SOPayments (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoID INTEGER NOT NULL,
  PaymentID INTEGER NOT NULL,
  FOREIGN KEY (SoID) REFERENCES SO(SoID),
  FOREIGN KEY (PaymentID) REFERENCES Payments(ID)
);

CREATE TABLE IF NOT EXISTS SoReturnTyres (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SoTyreID INTEGER NOT NULL,
  Qty INTEGER NOT NULL,
  ReturnDate TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Reason TEXT,
  CreatedAt DATETIME DEFAULT (datetime('now', 'localtime')),
  SoTyreStorageAllocationID INTEGER,
  StorageManagerID INTEGER,
  StorageManagerBatchID INTEGER,
  DOT TEXT,
  SalesReturnID INTEGER,
  StatusId INTEGER,
  FOREIGN KEY (SoTyreID) REFERENCES SoTyres(ID),
  FOREIGN KEY (SoTyreStorageAllocationID) REFERENCES SoTyreStorageAllocation(Id),
  FOREIGN KEY (SalesReturnID) REFERENCES SalesReturn(SalesReturnID),
  FOREIGN KEY (StatusId) REFERENCES SalesReturnStatusM(Id)
);
